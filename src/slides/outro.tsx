import React from "react";
import { AbsoluteFill } from "remotion";
import { C, F } from "../deck/theme";
import { POP, SlideDef, useSteps } from "../deck/steps";
import { highlight, Lang } from "../deck/Code";
import { clamp01 } from "../deck/ui";
import { useAmbient } from "../deck/clock";

/* A program writes a program: three examples from the lecture, the generated side types itself out. */
type Example = { title: string; lang: Lang; input: string[]; output: string[] };
const EXAMPLES: Example[] = [
  {
    title: "розгортання макросу",
    lang: "rkt",
    input: ["(unless (> x 5)", "  (displayln x))"],
    output: ["(when (not (> x 5))", "  (displayln x))"],
  },
  {
    title: "генератор вихідного коду",
    lang: "cs",
    input: ["[JsonSerializable(typeof(Point))]", "partial class Ctx", "  : JsonSerializerContext { }"],
    output: ["// <auto-generated/>", "partial class Ctx", "{", "  public JsonTypeInfo<Point> Point", "    => Create_Point(Options);", "}"],
  },
  {
    title: "згортання констант",
    lang: "js",
    input: ["const area = 2 * 3.14 * 10;"],
    output: ["const area = 62.8;"],
  },
];
const PERIOD = 8;
const TYPE_START = 1.2;
const CPS = 24;
const FADE = 0.5;

const PANEL_Y = 520;
const PANEL_H = 330;
const LX = 120;
const RX = 1020;
const PW = 780;

const Editor: React.FC<{ x: number; label: string; children: React.ReactNode }> = ({ x, label, children }) => (
  <div style={{ position: "absolute", left: x, top: PANEL_Y, width: PW, height: PANEL_H, borderRadius: 10, border: `1.5px solid ${C.line}`, background: C.panel, overflow: "hidden" }}>
    <div style={{ height: 44, borderBottom: `1.5px solid ${C.line}`, display: "flex", alignItems: "center", padding: "0 20px", fontFamily: F.head, fontStyle: "italic", fontSize: 26, color: C.dim }}>{label}</div>
    <div style={{ padding: "18px 24px", fontFamily: F.mono, fontWeight: 600, fontSize: 27, lineHeight: 1.5, color: C.text, whiteSpace: "pre", fontVariantLigatures: "none" }}>{children}</div>
  </div>
);

const Generator: React.FC<{ p: number }> = ({ p }) => {
  const t = useAmbient();
  const n = Math.floor(t / PERIOD);
  const ex = EXAMPLES[n % EXAMPLES.length];
  const local = t - n * PERIOD;
  const vis = Math.min(clamp01(local / FADE), clamp01((PERIOD - local) / FADE));
  let budget = Math.max(0, Math.floor((local - TYPE_START) * CPS));
  const typed: React.ReactNode[] = [];
  let done = false;
  ex.output.forEach((line, i) => {
    if (done) return;
    const take = Math.min(line.length, budget);
    budget -= line.length;
    const caret = take < line.length || i === ex.output.length - 1;
    if (take < line.length) done = true;
    typed.push(
      <div key={i} style={{ minHeight: "1.5em" }}>
        {highlight(line.slice(0, take), `o${i}`, ex.lang)}
        {caret && <span style={{ display: "inline-block", width: 3, height: 28, background: C.teal, marginLeft: 2, verticalAlign: "middle", opacity: Math.floor(t * 2) % 2 ? 1 : 0.2 }} />}
      </div>,
    );
  });
  const arrowP = clamp01((local - 0.6) / 0.5);
  const midY = PANEL_Y + PANEL_H / 2;
  return (
    <div style={{ position: "absolute", inset: 0, opacity: clamp01(p) }}>
      <div style={{ position: "absolute", left: 0, right: 0, top: PANEL_Y - 74, textAlign: "center", fontFamily: F.head, fontStyle: "italic", fontSize: 34, color: C.amber, opacity: vis }}>{ex.title}</div>
      <div style={{ opacity: vis }}>
        <Editor x={LX} label="програма">
          {ex.input.map((l, i) => (
            <div key={i} style={{ minHeight: "1.5em" }}>
              {highlight(l, `i${i}`, ex.lang)}
            </div>
          ))}
        </Editor>
        <svg width={1920} height={1080} style={{ position: "absolute", left: 0, top: 0, pointerEvents: "none" }}>
          <line x1={LX + PW + 16} y1={midY} x2={LX + PW + 16 + (RX - LX - PW - 40) * arrowP} y2={midY} stroke={C.dim} strokeWidth={2.5} />
          <polygon points={`${RX - 14},${midY} ${RX - 28},${midY - 8} ${RX - 28},${midY + 8}`} fill={C.dim} opacity={arrowP > 0.95 ? 1 : 0} />
        </svg>
        <Editor x={RX} label="згенерований код">{typed}</Editor>
      </div>
      <div style={{ position: "absolute", left: 0, right: 0, top: PANEL_Y + PANEL_H + 40, display: "flex", justifyContent: "center", gap: 14 }}>
        {EXAMPLES.map((_, i) => (
          <span key={i} style={{ width: 10, height: 10, borderRadius: 5, background: i === n % EXAMPLES.length ? C.amber : C.line }} />
        ))}
      </div>
    </div>
  );
};

const Outro: React.FC = () => {
  const { s } = useSteps();
  const words = ["Дякую", "за", "увагу!"];
  return (
    <AbsoluteFill style={{ background: `radial-gradient(ellipse at 50% 60%, #111a30 0%, #0a0f1d 75%)`, overflow: "hidden", userSelect: "none" }}>
      <Generator p={s(0, 20)} />
      <div style={{ position: "absolute", left: 0, right: 0, top: 90, textAlign: "center", fontFamily: F.head, fontWeight: 700, fontSize: 142, color: C.text }}>
        {words.map((w, i) => {
          const p = s(0, 6 + i * 6, POP);
          return (
            <span key={w} style={{ display: "inline-block", whiteSpace: "pre", opacity: clamp01(p), transform: `translateY(${(1 - p) * 40}px)` }}>
              {w + (i < words.length - 1 ? " " : "")}
            </span>
          );
        })}
      </div>
      <div style={{ position: "absolute", left: 0, right: 0, top: 262, textAlign: "center", fontFamily: F.head, fontStyle: "italic", fontWeight: 500, fontSize: 44, color: C.dim, opacity: clamp01(s(0, 30)) }}>
        Питання?
      </div>
      <div style={{ position: "absolute", right: 96, bottom: 52, fontFamily: F.mono, fontSize: 22, fontWeight: 600, color: C.faint, opacity: clamp01(s(0, 40)) }}>made with Claude Opus 5.5</div>
    </AbsoluteFill>
  );
};

export const outroSlide: SlideDef = { id: "thanks", title: "Дякую за увагу", steps: [300], C: Outro };
